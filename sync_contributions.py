"""Build the final contribution page from the ten step reports."""
import argparse
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
MEMBERS = ['Priyansh Rawat', 'Samarth Bhatnagar', 'Mayank Sinha']


def generate():
    roles = {name: [] for name in MEMBERS}
    for step in range(1, 11):
        filename = 'step_01_report.tex' if step == 1 else 'main.tex'
        path = ROOT / f'step{step}/latex' / filename
        text = path.read_text()
        sections = list(re.finditer(r'\\section\*?\{Contributions[^}]*\}', text))
        if not sections:
            raise ValueError(f'Contribution section missing in {path}')
        section = text[sections[-1].end():]
        for name in MEMBERS:
            match = re.search(re.escape(name) + r'\s*&\s*(.*?)\\\\', section, re.S)
            if not match:
                raise ValueError(f'{name} contribution missing in Step {step}')
            roles[name].append(re.sub(r'\s+', ' ', match.group(1)).strip())

    lines = [r'% Generated by sync_contributions.py from the individual step reports.',
             r'\section*{Contributions by step}', r'\begingroup',
             r'\renewcommand{\arraystretch}{1.06}']
    for name in MEMBERS:
        lines += [r'\textbf{' + name + r'}\par\smallskip',
                  r'\begin{tabularx}{\linewidth}{@{}p{13mm}X@{}}']
        lines += [f'Step {step} & {role}' + r'\\' for step, role in enumerate(roles[name], 1)]
        lines += [r'\end{tabularx}\par\vspace{4mm}']
    lines += [r'\endgroup', '']
    target = ROOT / 'final_report/latex/contributions.tex'
    result = '\n'.join(lines)
    if not target.exists() or target.read_text() != result:
        target.write_text(result)
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build', action='store_true', help='also rebuild the final PDF')
    args = parser.parse_args()
    target = generate()
    if args.build:
        folder = target.parent
        (folder / 'build').mkdir(exist_ok=True)
        for _ in range(2):
            run = subprocess.run(['pdflatex', '-interaction=nonstopmode', '-halt-on-error',
                                  '-output-directory=build', 'main.tex'], cwd=folder,
                                 stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            if run.returncode:
                raise RuntimeError(run.stdout[-2000:])
        shutil.copyfile(folder / 'build/main.pdf', folder.parent / 'Final_Report.pdf')
    print('Final contribution page synced from Steps 1-10.')


if __name__ == '__main__':
    main()
